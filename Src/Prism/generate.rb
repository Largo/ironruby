def cs_skimmer(field)
  case field.fetch("type")
  when "node" then "SkimNode();"
  when "node?" then "SkimOptionalNode();"
  when "node[]" then "SkimNodeList();"
  when "string" then "SkipString();"
  when "constant", "constant?", "uint32" then "LoadVarUInt();"
  when "constant[]" then "SkipVarUIntList();"
  when "location" then "LoadLocation();"
  when "location?" then "LoadOptionalLocation();"
  when "uint8" then "_pos++;"
  when "integer" then "LoadInteger();"
  when "double" then "_pos += 8;"
  end
end

# what the bridge must not put off: bridged later, these would warn (or fail) late
eager_nodes = %w[DefinedNode SingletonClassNode ClassNode ModuleNode]
nodes.each_with_index do |node, index|
  name = node.fetch("name")
  fields = node["fields"] || []
  loader_cs << "                case #{index + 1}: {\n"
  loader_cs << "                    _pos += 4;\n" if name == "DefNode"
  loader_cs << "                    LoadVarUInt(); // flags\n"
  loader_cs << "                    _contents |= ContentsEager;\n" if eager_nodes.include?(name)
  loader_cs << "                    _contents |= ContentsUsesBlock;\n" if name == "YieldNode"
  saved = false
  fields.each do |field|
    fname = field.fetch("name")
    if name == "DefNode" && fname == "parameters"
      # a nested method's use of its block is its own; what forces the outer one eager is not
      loader_cs << "                    uint outer = _contents;\n"
      loader_cs << "                    _contents = 0;\n"
      saved = true
    end
    if (name == "SuperNode" || name == "ForwardingSuperNode") && fname == "block"
      # super with no block of its own passes the method's block on
      loader_cs << "                    if (_buffer[_pos] == 0) _contents |= ContentsUsesBlock;\n"
    end
    if (name == "RegularExpressionNode" || name == "MatchLastLineNode") && fname == "unescaped"
      loader_cs << "                    SkipRegexpSource();\n"
      next
    end
    loader_cs << "                    #{cs_skimmer(field)}\n"
    if name == "DefNode" && fname == "body"
      loader_cs << "                    _contents = outer | (_contents & ContentsEager);\n"
    end
  end
  loader_cs << "                    return;\n"
  loader_cs << "                }\n"
end
loader_cs << <<~CS
                default:
                    throw new System.InvalidOperationException("Unknown prism node type: " + type);
            }
        }
    }
  }
CS

Dir.mkdir(out_dir) unless Dir.exist?(out_dir)
# Binary mode: on Windows Ruby a text-mode write would turn every "\n" into
# "\r\n", so the generated sources would differ byte-for-byte from the ones a
# Linux run produces. The generator is run in CI on both platforms.
File.binwrite(File.join(out_dir, "PrismNodes.Generated.cs"), nodes_cs.string)
File.binwrite(File.join(out_dir, "PrismLoader.Generated.cs"), loader_cs.string)
puts "generated #{nodes.size} node classes, #{flags.size} flag sets -> #{out_dir}"

# ---- PrismMeta.Generated.cs ----
# Reflection metadata for consumers that walk the tree generically (Ripper):
# the serialized token-type table and, per node, prism's own field names paired
# with the C# field they were emitted as.
meta_cs = StringIO.new
meta_cs << <<~CS
  // <auto-generated> generated by generate.rb from prism config.yml — do not edit </auto-generated>
  using System.Collections.Generic;

  namespace IronRuby.Prism {
      public static class PrismMeta {
          /// <summary>Token types indexed by prism's serialized token id (0 terminates a token list).</summary>
          public static readonly string[] TokenTypes = new string[] {
              null,
CS
config.fetch("tokens").each { |token| meta_cs << "            #{token.fetch("name").inspect},\n" }
meta_cs << <<~CS
          };

          /// <summary>Per node name, {prism field name, C# field name} pairs in prism's order.</summary>
          public static readonly Dictionary<string, string[][]> NodeFields = new Dictionary<string, string[][]> {
CS
nodes.each do |node|
  pairs = (node["fields"] || []).map { |f| "new string[] { #{f.fetch("name").inspect}, #{field_name(node, f).inspect} }" }
  meta_cs << "            { #{node.fetch("name").inspect}, new string[][] { #{pairs.join(", ")} } },\n"
end
meta_cs << <<~CS
          };
      }
  }
CS
File.binwrite(File.join(out_dir, "PrismMeta.Generated.cs"), meta_cs.string)
puts "generated #{config.fetch("tokens").size} token types -> #{out_dir}/PrismMeta.Generated.cs"
