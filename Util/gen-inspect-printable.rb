#!/usr/bin/env ruby
# Generates Src/Ruby/Builtins/InspectPrintable.Generated.cs: for each ASCII compatible
# encoding, the bytes 0x80-0xFF that String#inspect writes as themselves when they are a
# character of their own and the inspected string is in the encoding #inspect answers in
# (Encoding.default_internal, else default_external). MRI asks rb_enc_isprint, that is
# Onigmo's ctype table for the encoding, and those tables are each their own: the IBM and
# mac code pages have no printable byte above 0x7F (Onigmo makes them replicas of
# ASCII-8BIT), the Windows ones leave out some punctuation Unicode would call printable.
# So they are asked of CRuby, byte by byte. A valid character of more than one byte is
# printable in every encoding that has them, which the generator checks for the two byte
# ones.
#
#   ruby Util/gen-inspect-printable.rb [output.cs]

abort "run this with CRuby (it asks CRuby's own String#inspect)" if RUBY_ENGINE != "ruby"

out = ARGV[0] || File.expand_path("../Src/Ruby/Builtins/InspectPrintable.Generated.cs", __dir__)
$VERBOSE = nil

def raw?(s) = s.inspect.b == "\"#{s.b}\"".b

encodings = Encoding.list.reject(&:dummy?).select(&:ascii_compatible?)
encodings.reject! { |e| %w[ASCII-8BIT US-ASCII CESU-8].include?(e.name) || e.name.start_with?("UTF") }

tables = {}
encodings.each do |e|
  Encoding.default_internal = e
  printable = (0x80..0xff).select do |b|
    s = [b].pack("C").force_encoding(e)
    s.valid_encoding? && s.length == 1 && raw?(s)
  end
  (0x80..0xff).each do |a|
    (0x00..0xff).each do |b|
      s = [a, b].pack("CC").force_encoding(e)
      next unless s.valid_encoding? && s.length == 1
      abort "#{e.name}: #{s.unpack1('H*')} is a character #inspect escapes" unless raw?(s)
    end
  end
  tables[e.name] = printable
ensure
  Encoding.default_internal = nil
end

def mask(bytes, half) = bytes.select { |b| (b - 0x80) / 64 == half }.sum { |b| 1 << ((b - 0x80) % 64) }

lines = []
lines << "// <auto-generated> generated by Util/gen-inspect-printable.rb from CRuby #{RUBY_VERSION} - do not edit </auto-generated>"
lines << "namespace IronRuby.Builtins {"
lines << "    internal static partial class InspectPrintable {"
lines << "        // Encoding name, then the printable bytes 0x80-0xBF and 0xC0-0xFF as bit masks; an"
lines << "        // encoding not listed has none."
lines << "        private static readonly object[] _tables = new object[] {"
tables.sort.each do |name, bytes|
  next if bytes.empty?
  lines << format("            \"%s\", 0x%016XUL, 0x%016XUL,", name, mask(bytes, 0), mask(bytes, 1))
end
lines << "        };"
lines << "    }"
lines << "}"
File.write(out, lines.join("\r\n") + "\r\n")
puts "#{out}: #{tables.size} encodings, #{tables.count { |_, b| !b.empty? }} with printable bytes above 0x7F"
