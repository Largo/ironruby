#!/usr/bin/env bash
# Builds libironruby-capi, the native half of IronRuby's Ruby C API (Src/Ruby/CApi):
#
#   Util/build-capi.sh [OUTDIR]     # default: Src/Ruby/CApi/native/build
#
# The shim is capi.c (trampolines, unwinding, the variadic functions) plus
# forwarders.generated.c (one exported rb_* function per line of Src/Ruby/CApi/functions.txt,
# from Util/capi/generate.rb), plus a stub for every other function the shipped headers declare:
# it raises NotImplementedError, so an extension that uses something IronRuby lacks still loads
# and fails only if it calls it. Ruby.csproj ships the result next to IronRuby.dll, as
# IronRuby.Prism.csproj does libprism.
#
# Linux x64 for now (the headers' config.h is x86_64-linux); set CC to use another compiler.
set -euo pipefail
# sort and comm below must agree on the order: in en_GB.UTF-8, say, sort puts `_Exit` where
# comm does not expect it, comm stops with "not in sorted order" and the build with it.
export LC_ALL=C

IR_ROOT=$(cd "$(dirname "$0")/.." && pwd)
SRC="$IR_ROOT/Src/Ruby/CApi/native"
OUT=${1:-$SRC/build}
CC=${CC:-gcc}
INC="$IR_ROOT/Src/StdLib/include"

# Windows: MinGW gcc (MSYS2 UCRT64 or the RubyInstaller DevKit), from Git Bash or an MSYS2
# shell. The DLL exports every function and the global VALUEs; extensions link against its
# import library, libironruby-capi.dll.a, which is shipped beside it.
case "$(uname -s)" in
  Linux)
    LIB=libironruby-capi.so; ARCH=x86_64-linux; PLATFORM_CFLAGS="-fPIC -fvisibility=default"
    LINKFLAGS="" ;;
  MINGW*|MSYS*)
    LIB=libironruby-capi.dll; ARCH=x64-mingw-ucrt
    # RUBY_EXPORT: the global VALUEs are defined here, not imported
    PLATFORM_CFLAGS="-DRUBY_EXPORT -D_WIN32_WINNT=0x0600 -D__MINGW_USE_VC2005_COMPAT"
    LINKFLAGS="-Wl,--export-all-symbols -Wl,--out-implib,OUTDIR/libironruby-capi.dll.a -static-libgcc" ;;
  *) echo "build-capi.sh: only Linux and Windows (MinGW) are supported so far" >&2; exit 1 ;;
esac
ARCH_INC="$INC/$ARCH"

if command -v ruby >/dev/null 2>&1; then
  ruby "$IR_ROOT/Util/capi/generate.rb" >/dev/null
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
CFLAGS="-O2 -g $PLATFORM_CFLAGS -Wall -Wno-unused-function -I$INC -I$ARCH_INC"

"$CC" $CFLAGS -c "$SRC/capi.c" -o "$tmp/capi.o"
"$CC" $CFLAGS -c "$SRC/st.c" -o "$tmp/st.o"
"$CC" $CFLAGS -c "$SRC/forwarders.generated.c" -o "$tmp/forwarders.o"

# Stubs for everything declared and not defined above.
nm --defined-only -g "$tmp/capi.o" "$tmp/st.o" "$tmp/forwarders.o" | awk 'NF == 3 { print $3 }' | sort -u > "$tmp/defined.txt"
if command -v ruby >/dev/null 2>&1; then
  ruby "$IR_ROOT/Util/capi/prototypes.rb" --names > "$tmp/declared.txt"
  # the platform's own declarations (rb_w32_* on Windows) are added to the committed list
  sort -u "$SRC/declared.txt" "$tmp/declared.txt" -o "$SRC/declared.txt"
fi
# and for CRuby's other exported functions (cruby-exports.txt, from `nm libruby-static.a`): some
# extensions declare one themselves (hash_spec.c: rb_ident_hash_new), and a missing symbol
# would fail the whole dlopen rather than the one call
cat "$SRC/declared.txt" "$SRC/cruby-exports.txt" | grep -E '^(rb_|ruby_|onig|st_)' | sort -u | comm -23 - "$tmp/defined.txt" > "$tmp/stubs.txt"
{
  echo '/* Generated by Util/build-capi.sh: functions the headers declare that IronRuby does not implement yet. */'
  echo 'void rb_ir_unimplemented(const char *name);'
  while read -r name; do
    echo "void $name(void) { rb_ir_unimplemented(\"$name\"); }"
  done < "$tmp/stubs.txt"
} > "$tmp/stubs.c"
"$CC" -O1 $PLATFORM_CFLAGS -w -c "$tmp/stubs.c" -o "$tmp/stubs.o"

mkdir -p "$OUT"
"$CC" -shared -o "$OUT/$LIB" "$tmp/capi.o" "$tmp/st.o" "$tmp/forwarders.o" "$tmp/stubs.o" ${LINKFLAGS//OUTDIR/$OUT}
echo "$OUT/$LIB: $(wc -l < "$tmp/defined.txt") functions defined, $(wc -l < "$tmp/stubs.txt") stubs"
