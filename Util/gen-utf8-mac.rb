#!/usr/bin/env ruby
# Generates Src/Ruby/Runtime/Utf8MacTables.Generated.cs: the tables of MRI's UTF8-MAC
# converters (enc/trans/utf8_mac.c), read off a CRuby that has them.
#
#   ruby Util/gen-utf8-mac.rb [output.cs]
#
# Converting to UTF8-MAC writes each character in its decomposed form, as HFS+ names
# files; converting from it composes a character with the one after it where the pair
# names one. The tables are Apple's frozen list, not Unicode's decompositions: U+0390, the
# Balinese letters and the Greek oxia forms, among others, stay whole, and U+2000-U+2FFF,
# U+F900-U+FAFF and U+2F800-U+2FAFF are never decomposed. So they are asked of CRuby
# itself, character by character, rather than built from the UCD. Hangul syllables are
# left out: both directions do them by arithmetic (UnicodeData's Hangul algorithm), as
# CRuby's tables agree with for all 11172 of them.
#
# Composition pairs are the decompositions read backwards - a character's last mark onto
# the character its other code points compose to - kept where CRuby composes them, which
# leaves out the singletons and Unicode's composition exclusions (U+0958...). That they
# are all CRuby composes is checked against UnicodeNormalize's composition table.

abort "run this with CRuby (it asks CRuby's own UTF8-MAC converters)" if RUBY_ENGINE != "ruby"

out = ARGV[0] || File.expand_path("../Src/Ruby/Runtime/Utf8MacTables.Generated.cs", __dir__)

def hangul?(cp) = (0xAC00..0xD7A3).cover?(cp)
def from_mac(cps) = cps.pack("U*").force_encoding("UTF8-MAC").encode("UTF-8").unpack("U*")

decompositions = {}
undefined_from = nil
(0..0x10FFFF).each do |cp|
  next if (0xD800..0xDFFF).cover?(cp)
  begin
    d = [cp].pack("U").encode("UTF8-MAC").unpack("U*")
  rescue Encoding::UndefinedConversionError
    undefined_from ||= cp
    next
  end
  abort "U+#{cp.to_s(16)} converts after U+#{undefined_from.to_s(16)} did not" if undefined_from
  decompositions[cp] = d if d != [cp] && !hangul?(cp)
end
hangul = (0xAC00..0xD7A3).all? do |cp|
  s = cp - 0xAC00
  d = [0x1100 + s / 588, 0x1161 + (s % 588) / 28]
  d << 0x11A7 + s % 28 if s % 28 != 0
  [cp].pack("U").encode("UTF8-MAC").unpack("U*") == d && from_mac(d) == [cp]
end
abort "CRuby's Hangul syllables are not the algorithm's" unless hangul

inverse = decompositions.to_h { |cp, d| [d, cp] }
pairs = {}
decompositions.each do |cp, d|
  next if d.size < 2
  head = d.size == 2 ? d[0] : inverse[d[0..-2]]
  pairs[[head, d[-1]]] = cp if head && from_mac([head, d[-1]]) == [cp]
end

require "unicode_normalize/tables"
UnicodeNormalize::COMPOSITION_TABLE.each_key do |ab|
  a, b = ab.unpack("U*")
  next if pairs.key?([a, b]) || hangul?(a)
  r = from_mac([a, b])
  abort "CRuby composes U+#{a.to_s(16)} U+#{b.to_s(16)}, which the pairs leave out" if r != [a, b]
end

def cs(cps) = cps.map { |c| c > 0xFFFF ? format("\\U%08X", c) : format("\\u%04X", c) }.join

lines = []
lines << "// <auto-generated> generated by Util/gen-utf8-mac.rb from CRuby #{RUBY_VERSION}'s UTF8-MAC converters - do not edit </auto-generated>"
lines << "namespace IronRuby.Runtime {"
lines << "    internal static partial class Utf8MacTables {"
lines << "        // The first code point UTF-8 to UTF8-MAC has no conversion for; it has none for any after it either."
lines << "        internal const int FirstUndefined = 0x#{undefined_from.to_s(16).upcase};"
lines << ""
lines << "        // Characters (but Hangul syllables) and the code points UTF8-MAC writes them as, sorted."
lines << "        private static readonly int[] _decomposed = new int[] {"
decompositions.keys.each_slice(12) { |s| lines << "            " + s.map { |c| format("0x%04X,", c) }.join(" ") }
lines << "        };"
lines << "        private static readonly string[] _decompositions = new string[] {"
decompositions.values.each_slice(6) { |s| lines << "            " + s.map { |d| "\"#{cs(d)}\"," }.join(" ") }
lines << "        };"
lines << ""
lines << "        // The pairs UTF8-MAC to UTF-8 composes, first, second and result, sorted."
lines << "        private static readonly int[] _pairs = new int[] {"
pairs.sort.each_slice(4) { |s| lines << "            " + s.map { |(a, b), c| format("0x%04X, 0x%04X, 0x%04X,", a, b, c) }.join(" ") }
lines << "        };"
lines << "    }"
lines << "}"
File.write(out, lines.join("\r\n") + "\r\n")
puts "#{out}: #{decompositions.size} decompositions, #{pairs.size} pairs, undefined from U+#{undefined_from.to_s(16)}"
